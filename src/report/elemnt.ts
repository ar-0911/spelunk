import type { CallNode } from "../query/trace.js";
import { diagramMermaid } from "./diagram.js";
import { sourceUrl, type Report } from "./model.js";

/**
 * The field guide as an Elemnt page, for `spelunk publish`: the same content
 * as SPELUNK.md, laid out with Elemnt's components (hero, big numbers,
 * diagram, cards, sortable tables, collapsible detail) so the team reads it
 * where the rest of their docs live.
 */

/** Elemnt rejects page sources over 500,000 characters; stay well under. */
export const MAX_SOURCE = 480_000;

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
/** Text for a directive label: no brackets, one line. */
const label = (s: string) => s.replace(/[[\]]/g, "").replace(/\s+/g, " ").trim().slice(0, 120);
/** Text for a quoted attribute. */
const attr = (s: string) => s.replace(/"/g, "'").replace(/\s+/g, " ").trim();
/** Code-derived text in prose: backticked, so nothing in it is read as Markdown or a directive. */
const code = (s: string) => `\`${s.replace(/`/g, "'").replace(/\s+/g, " ").slice(0, 140)}\``;
const n = (x: number) => x.toLocaleString("en");
/** Big numbers for the stats row: 13,630 → 13.6k, so they fit their tile. */
const big = (x: number) => (x >= 1e6 ? `${(x / 1e6).toFixed(1)}M` : x >= 1e4 ? `${(x / 1e3).toFixed(1)}k` : n(x));
/** A card title short enough for its column: the last two folders of a long path. */
const short = (p: string) => (p.length > 26 && p.split("/").length > 2 ? `…/${p.split("/").slice(-2).join("/")}` : p);

function render(r: Report, rows: number): string {
  const link = (path: string, line?: number) => {
    const text = `\`${path}${line ? `:${line}` : ""}\``;
    const url = sourceUrl(r, path, line);
    return url ? `[${text}](${url})` : text;
  };
  const tree = (nodes: CallNode[], depth = 0): string[] => nodes.flatMap((x) => [`${"  ".repeat(depth)}- \`${x.name}\` ${link(x.path, x.line)}`, ...tree(x.children, depth + 1)]);
  const o = r.overview;
  const home = r.remote ? sourceUrl(r, "")?.replace(/\/(blob|src|browse|-\/blob)\/.*$|\/browse\?.*$/, "") : undefined;

  const out: string[] = [
    "---",
    `title: "${attr(`${r.name}: codebase map`)}"`,
    `summary: "${attr(o?.oneLiner ?? `How ${r.name} is put together: its parts, how to run it, where requests go and where bugs hide.`)}"`,
    "---",
    "",
    `:::hero[${label(r.name)}]{eyebrow="Codebase map, generated by Spelunk" art=orbit}`,
    o ? `${o.oneLiner} ${o.whatItDoes}` : `A map of ${r.name} for anyone new to it: the big parts and how they connect, how to run it, where requests go, and where bugs tend to hide.`,
    "",
    ["[Run it](#run-it)", "[Code map](#code-map)", ...(home ? [`[Repository](${home})`] : [])].join(" "),
    ":::",
    "",
    ":::stats",
    `::stat[${big(r.stats.codeFiles)}]{label="Code files" note="${r.modules.length} modules"}`,
    `::stat[${big(r.stats.codeLines)}]{label="Lines of code"}`,
    `::stat[${big(r.stats.routes)}]{label="HTTP routes"}`,
    `::stat[${big(r.stats.tests)}]{label="Test files"}`,
    ":::",
    "",
    // The commit, not the time, so re-publishing an unchanged repo produces the same page.
    `_Generated ${r.commit ? `from commit ${r.commit.slice(0, 10)}` : r.generatedAt.slice(0, 10)}. Languages: ${r.languages.slice(0, 6).map((l) => `${l.language} (${n(l.lines)} lines)`).join(", ")}._`,
    "",
  ];

  if (o?.architecture) out.push("## How it fits together", "", o.architecture, "");
  if (r.entries.length) out.push("## Where it starts", "", ...r.entries.slice(0, 10).map((e) => `- ${link(e.path)}: ${e.label}`), "");

  out.push("## Run it", "");
  if (o?.runLocally.length) out.push(":::steps", ...o.runLocally.map((s, i) => `${i + 1}. ${/^\*\*/.test(s) ? s : `**Step ${i + 1}.** ${s}`}`), ":::", "");
  const cmds = r.commands.filter((c) => c.kind !== "ci").slice(0, rows);
  if (cmds.length) out.push(':::datagrid{caption="Commands the project defines"}', "| Command | Runs | Defined in |", "| --- | --- | --- |", ...cmds.map((c) => `| \`${cell(c.name)}\` | \`${cell(c.command.slice(0, 90))}\` | ${link(c.manifest)} |`), ":::", "");
  if (!o?.runLocally.length && !cmds.length) out.push("No run commands found in the manifests.", "");

  // Big repos: the diagram shows the largest modules so it stays readable.
  const shown = [...r.modules].sort((a, b) => b.lines - a.lines).slice(0, 30);
  const keep = new Set(shown.map((m) => m.path));
  out.push(
    "## Architecture",
    "",
    `Each box is a directory; arrows point from a module to what it imports.${r.modules.length > shown.length ? ` The ${shown.length} largest of ${r.modules.length} modules are shown.` : ""}`,
    "",
    `:::diagram{caption="Modules and their imports"}`,
    "```mermaid",
    diagramMermaid(shown.map((m) => ({ ...m, dependsOn: m.dependsOn.filter((d) => keep.has(d.path)) }))),
    "```",
    ":::",
    "",
  );

  out.push("## Code map", "");
  const top = shown.slice(0, 8);
  out.push(`::::cards{cols=2}`);
  for (const m of top) {
    const most = [...m.files].sort((a, b) => b.usedBy - a.usedBy)[0]?.path ?? "";
    out.push(`:::card[${label(short(m.path || "(root)"))}]{icon="📁"}`, `${n(m.files.length)} files, ${n(m.lines)} lines. ${m.explanation ? m.explanation.summary.split(/(?<=[.!?])\s/)[0] : `Most used: ${code(most.split("/").pop()!)}.`}`, ":::");
  }
  out.push("::::", "");
  for (const m of r.modules.slice(0, rows)) {
    const e = m.explanation;
    out.push(`:::details[${label(m.path || "(root)")}: ${n(m.files.length)} files]`);
    if (e) {
      out.push(e.summary, "", ...e.responsibilities.map((x) => `- ${x}`), "");
      if (e.gotchas.length) out.push(`**Gotchas:** ${e.gotchas.join(" ")}`, "");
    }
    if (m.dependsOn.length) out.push(`Depends on ${m.dependsOn.slice(0, 10).map((d) => code(d.path || "(root)")).join(", ")}.`, "");
    const roles = new Map(e?.keyFiles.map((k) => [k.path, k.role]));
    const files = [...m.files].sort((a, b) => b.usedBy - a.usedBy).slice(0, Math.min(25, rows));
    out.push("| File | Lines | Used by | What it is |", "| --- | --- | --- | --- |", ...files.map((f) => `| ${link(f.path)} | ${f.lines} | ${f.usedBy} | ${cell(roles.get(f.path) ?? f.doc?.slice(0, 160) ?? "")} |`));
    if (m.files.length > files.length) out.push("", `And ${n(m.files.length - files.length)} more files.`);
    out.push(":::", "");
  }
  if (r.modules.length > rows) out.push(`And ${r.modules.length - rows} more modules. Run \`spelunk map\` for all of them.`, "");

  if (r.routes.length) {
    out.push("## Routes", "", ':::datagrid{caption="HTTP routes and who calls them"}', "| Method | Path | Handler | Called from |", "| --- | --- | --- | --- |");
    out.push(...r.routes.slice(0, rows * 2).map((x) => `| ${x.method} | \`${cell(x.path)}\` | ${link(x.file, x.line)} | ${x.callers.slice(0, 3).map((c) => link(c.path, c.line)).join(", ")} |`), ":::", "");
  }

  if (o?.flows.length || r.staticFlows.length) {
    out.push("## Follow a request", "");
    for (const f of o?.flows ?? []) out.push(`### ${f.name}`, "", f.summary, "", ":::steps", ...f.steps.map((s, i) => `${i + 1}. **${label(s.what).replace(/\*/g, "")}** ${link(s.path, s.line)}${s.symbol ? ` (${code(s.symbol)})` : ""}`), ":::", "");
    for (const f of r.staticFlows.slice(0, 5)) {
      out.push(`:::details[${label(f.label)}: call tree]`, `Handler ${link(f.path, f.line)}${f.callers.length ? `, called from ${f.callers.slice(0, 3).map((c) => link(c.path, c.line)).join(", ")}` : ""}.`, "", ...tree(f.tree), ":::", "");
    }
  }

  out.push("## When something breaks", "");
  const d = o?.debugging;
  if (d) {
    out.push(":::callout[First checks]{type=tip}", ...d.firstChecks.map((x) => `- ${x}`), ":::", "", "Where the logs are:", "", ...d.logs.map((x) => `- ${x}`), "");
    if (d.failurePoints.length) out.push(':::datagrid{caption="Common failures"}', "| Symptom | Likely cause | Where to look |", "| --- | --- | --- |", ...d.failurePoints.map((p) => `| ${cell(p.symptom)} | ${cell(p.likelyCause)} | ${cell(p.whereToLook)} |`), ":::", "");
  }
  out.push(
    ":::steps",
    "1. **Copy the exact error.** Reproduce it and copy the message or stack trace.",
    '2. **Find where it comes from.** `spelunk error "<the error>"` maps it to the line that raised or logged it.',
    "3. **Follow the code.** `spelunk trace <route or function>` shows who calls it and what it calls.",
    "4. **Check the risks below** for that file: swallowed errors and hotspots are the usual suspects.",
    ":::",
    "",
  );

  if (r.env.length) {
    const missing = r.env.filter((e) => e.readAt.length && !e.documented);
    out.push("## Configuration", "");
    if (missing.length) out.push(`:::callout[${missing.length} settings aren't in the example .env]{type=warn}`, `A fresh setup will miss ${missing.slice(0, 8).map((e) => code(e.name)).join(", ")}${missing.length > 8 ? " and more" : ""}.`, ":::", "");
    out.push(':::datagrid{caption="Environment variables"}', "| Variable | Read at | In .env example |", "| --- | --- | --- |", ...r.env.slice(0, rows * 2).map((e) => `| \`${cell(e.name)}\` | ${e.readAt.slice(0, 3).map((l) => link(l.path, l.line)).join(", ") || "never read"} | ${e.documented ? "yes" : "**no**"} |`), ":::", "");
  }

  out.push("## Where bugs hide", "");
  if (!r.risks.length) out.push("Nothing flagged.", "");
  for (const g of r.risks) {
    const sev = g.items.some((x) => x.severity === "high") ? "danger" : g.items.some((x) => x.severity === "medium") ? "warn" : "muted";
    out.push(`:::details[${label(g.kind.replace(/-/g, " "))}: ${g.items.length}]`, `:badge[${g.items.length}]{tone=${sev}} ${g.info}`, "");
    for (const x of g.items.slice(0, Math.min(15, rows))) out.push(`- **${x.severity}** ${cell(x.title)} ${x.locations.slice(0, 3).map((l) => link(l.path, l.line)).join(", ")}`);
    if (g.items.length > Math.min(15, rows)) out.push(`- And ${g.items.length - Math.min(15, rows)} more (\`spelunk risks --kind ${g.kind}\`)`);
    out.push(":::", "");
  }

  if (r.tests.length) {
    out.push("## Tests", "", ':::datagrid{caption="Test files and what they cover"}', "| Test | Covers |", "| --- | --- |", ...r.tests.slice(0, rows * 2).map((t) => `| ${link(t.path)} | ${t.covers.slice(0, 4).map((c) => `\`${cell(c)}\``).join(", ")}${t.covers.length > 4 ? ", …" : ""} |`), ":::", "");
  }

  if (o?.glossary.length) out.push("## Words this team uses", "", ...o.glossary.map((g) => `- **${g.term}**: ${g.meaning}`), "");
  out.push("---", "", "_This page is regenerated by `spelunk publish`; edits made here are replaced on the next run._", "");
  return out.join("\n");
}

/** Elemnt page source for the report, trimmed until it fits Elemnt's size limit. */
export function renderElemnt(r: Report): string {
  for (const rows of [60, 30, 15, 8, 4]) {
    const src = render(r, rows);
    if (src.length <= MAX_SOURCE) return src;
  }
  throw new Error(`The map of ${r.name} is too big for one Elemnt page, even trimmed. Publish part of it with --only.`);
}

export interface PublishOptions {
  /** Base URL of the Elemnt server, e.g. https://docs.example.com */
  url: string;
  token: string;
  space: string;
  /** Page path inside the space, e.g. "codebase/spelunk". */
  path: string;
  message?: string;
  /** Create or leave the page as a draft instead of publishing it. */
  draft?: boolean;
  fetch?: typeof fetch;
}

export interface PublishResult {
  action: "created" | "updated" | "unchanged";
  url: string;
}

/** Creates the page, or updates it in place (keeping its history), via Elemnt's API. */
export async function publishToElemnt(source: string, o: PublishOptions): Promise<PublishResult> {
  const f = o.fetch ?? fetch;
  const base = o.url.replace(/\/+$/, "");
  if (!/^https?:\/\//.test(base)) throw new Error(`Elemnt URL must start with https:// (got "${o.url}").`);
  const path = o.path.replace(/^\/+|\/+$/g, "");
  const call = async <T>(method: string, route: string, body?: unknown): Promise<T> => {
    const res = await f(`${base}${route}`, {
      method,
      headers: { Authorization: `Bearer ${o.token}`, Accept: "application/json", ...(body ? { "Content-Type": "application/json" } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {}),
    });
    const json = (await res.json().catch(() => ({}))) as T & { error?: string };
    if (!res.ok) {
      const why = json.error ?? res.statusText;
      if (res.status === 401) throw new Error(`Elemnt rejected the token (${why}). Create an API token in Elemnt under Settings → API tokens.`);
      if (res.status === 403) throw new Error(`This token can't write to the "${o.space}" space (${why}).`);
      throw new Error(`Elemnt ${method} ${route} failed (${res.status}): ${why}`);
    }
    return json;
  };

  const space = encodeURIComponent(o.space);
  const tree = await call<{ pages: { id: string; path: string }[] }>("GET", `/api/spaces/${space}/tree`);
  const existing = tree.pages.find((p) => p.path === path);
  const message = o.message ?? "Updated by spelunk publish";
  if (!existing) {
    // Elemnt pages live in a tree; parents have to exist before a child can be created.
    const have = new Set(tree.pages.map((p) => p.path));
    const parts = path.split("/");
    for (let i = 1; i < parts.length; i++) {
      const parent = parts.slice(0, i).join("/");
      if (have.has(parent)) continue;
      const title = parts[i - 1]!.replace(/[-_]+/g, " ").replace(/^./, (c) => c.toUpperCase());
      await call("POST", `/api/spaces/${space}/pages`, { path: parent, source: `# ${title}\n\nCodebase maps generated by Spelunk.\n`, message: "Created by spelunk publish" });
    }
    const created = await call<{ url?: string }>("POST", `/api/spaces/${space}/pages`, { path, source, message, ...(o.draft ? { draft: true } : {}) });
    return { action: "created", url: created.url ? new URL(created.url, base).href : `${base}/${o.space}/${path}` };
  }
  const page = await call<{ headRevisionId: string; source: string; url?: string }>("GET", `/api/pages/${encodeURIComponent(existing.id)}`);
  const url = page.url ? new URL(page.url, base).href : `${base}/${o.space}/${path}`;
  // Nothing changed since the last run (CI on a docs-only merge): don't add a revision.
  if (page.source === source) return { action: "unchanged", url };
  await call("PUT", `/api/pages/${encodeURIComponent(existing.id)}`, { source, baseRevisionId: page.headRevisionId, message, publish: !o.draft });
  return { action: "updated", url };
}
