import type { CallNode } from "../query/trace.js";
import { diagramMermaid } from "./diagram.js";
import { sourceUrl, type Report } from "./model.js";

/**
 * The field guide as Markdown (SPELUNK.md): the same sections as the HTML
 * page minus search, with a Mermaid diagram GitHub renders in place.
 */

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderMarkdown(r: Report): string {
  const link = (path: string, line?: number) => {
    const text = `\`${path}${line ? `:${line}` : ""}\``;
    const url = sourceUrl(r, path, line);
    return url ? `[${text}](${url})` : text;
  };
  const tree = (nodes: CallNode[], depth = 0): string[] => nodes.flatMap((n) => [`${"  ".repeat(depth)}- \`${n.name}\` ${link(n.path, n.line)}`, ...tree(n.children, depth + 1)]);

  const out: string[] = [`# ${r.name}: field guide`, ""];
  out.push(`_Generated by Spelunk on ${r.generatedAt.slice(0, 10)}${r.commit ? ` at \`${r.commit.slice(0, 10)}\`` : ""}. ${r.stats.codeFiles} code files, ${r.stats.codeLines.toLocaleString("en")} lines, ${r.stats.routes} routes, ${r.stats.tests} test files._`, "");

  out.push("## Start here", "");
  if (r.overview) out.push(`**${r.overview.oneLiner}**`, "", r.overview.whatItDoes, "", r.overview.architecture, "");
  out.push(`Languages: ${r.languages.map((l) => `${l.language} (${l.files} files, ${l.lines.toLocaleString("en")} lines)`).join(", ")}.`, "");
  if (r.entries.length) out.push("Entry points:", "", ...r.entries.map((e) => `- ${link(e.path)}: ${e.label}`), "");

  out.push("## Run it", "");
  if (r.overview?.runLocally.length) out.push(...r.overview.runLocally.map((s, i) => `${i + 1}. ${s}`), "");
  const cmds = r.commands.filter((c) => c.kind !== "ci");
  if (cmds.length) out.push("| Command | Runs | Defined in |", "|---|---|---|", ...cmds.slice(0, 40).map((c) => `| \`${cell(c.name)}\` | \`${cell(c.command.slice(0, 90))}\` | ${link(c.manifest)} |`), "");

  out.push("## Architecture", "", "Each box is a directory; arrows point from a module to what it imports.", "", "```mermaid", diagramMermaid(r.modules), "```", "");

  out.push("## Code map", "");
  for (const m of r.modules) {
    out.push(`### ${m.path || "(root)"}`, "", `${m.files.length} files, ${m.lines.toLocaleString("en")} lines${m.owner ? `, in ${link(m.owner)}` : ""}.${m.dependsOn.length ? ` Depends on ${m.dependsOn.map((d) => `\`${d.path || "(root)"}\``).join(", ")}.` : ""}`, "");
    const e = m.explanation;
    if (e) {
      out.push(e.summary, "", ...e.responsibilities.map((x) => `- ${x}`), "");
      if (e.gotchas.length) out.push("Gotchas:", "", ...e.gotchas.map((x) => `- ${x}`), "");
    }
    const roles = new Map(e?.keyFiles.map((k) => [k.path, k.role]));
    const files = [...m.files].sort((a, b) => b.usedBy - a.usedBy).slice(0, 25);
    out.push("| File | Lines | Used by | What it is |", "|---|---:|---:|---|", ...files.map((f) => `| ${link(f.path)} | ${f.lines} | ${f.usedBy} | ${cell(roles.get(f.path) ?? f.doc ?? "")} |`));
    if (m.files.length > files.length) out.push(`| … ${m.files.length - files.length} more | | | |`);
    out.push("");
  }

  if (r.routes.length) {
    out.push("## Routes", "", "| Method | Path | Handler | Called from |", "|---|---|---|---|");
    out.push(...r.routes.map((x) => `| ${x.method} | \`${cell(x.path)}\` | ${link(x.file, x.line)} | ${x.callers.slice(0, 3).map((c) => link(c.path, c.line)).join(", ")} |`), "");
  }

  out.push("## Flows", "");
  if (r.overview?.flows.length) {
    for (const f of r.overview.flows) out.push(`### ${f.name}`, "", f.summary, "", ...f.steps.map((s, i) => `${i + 1}. ${s.what} ${link(s.path, s.line)}${s.symbol ? ` (\`${s.symbol}\`)` : ""}`), "");
  }
  for (const f of r.staticFlows) {
    out.push(`### ${f.label} (call tree)`, "", `Handler ${link(f.path, f.line)}${f.callers.length ? `, called from ${f.callers.slice(0, 3).map((c) => link(c.path, c.line)).join(", ")}` : ""}.`, "", ...tree(f.tree), "");
  }
  if (!r.overview?.flows.length && !r.staticFlows.length) out.push("No flows found. Run `spelunk trace <route or function>` to follow one by hand.", "");

  out.push("## Debugging", "");
  const d = r.overview?.debugging;
  if (d) {
    out.push("First checks:", "", ...d.firstChecks.map((x) => `- ${x}`), "", "Where the logs are:", "", ...d.logs.map((x) => `- ${x}`), "");
    if (d.failurePoints.length) out.push("| Symptom | Likely cause | Where to look |", "|---|---|---|", ...d.failurePoints.map((p) => `| ${cell(p.symptom)} | ${cell(p.likelyCause)} | ${cell(p.whereToLook)} |`), "");
  }
  out.push("A routine that works on any repo:", "", "1. Reproduce it and copy the exact error text.", "2. `spelunk where \"<words from the error>\"` to find the code that raises or logs it.", "3. `spelunk trace <route or function>` to see who calls it and what it calls.", "4. Check the risks below for that file: swallowed errors and hotspots are the usual suspects.", "");
  if (r.errorLogs.length) out.push("<details><summary>Where errors are logged (" + r.errorLogs.length + ")</summary>", "", ...r.errorLogs.slice(0, 80).map((l) => `- ${link(l.path, l.line)} \`${cell(l.text.slice(0, 100))}\``), "", "</details>", "");

  if (r.env.length) {
    out.push("## Configuration", "", "| Variable | Read at | In .env example |", "|---|---|---|");
    out.push(...r.env.map((e) => `| \`${e.name}\` | ${e.readAt.slice(0, 3).map((l) => link(l.path, l.line)).join(", ") || "never read"} | ${e.documented ? "yes" : "**no**"} |`), "");
  }

  out.push("## Risks", "");
  if (!r.risks.length) out.push("Nothing flagged.", "");
  for (const g of r.risks) {
    out.push(`### ${g.kind} (${g.items.length})`, "", g.info, "");
    for (const x of g.items.slice(0, 15)) out.push(`- **${x.severity}** ${x.title}: ${x.detail} ${x.locations.slice(0, 3).map((l) => link(l.path, l.line)).join(", ")}`);
    if (g.items.length > 15) out.push(`- … ${g.items.length - 15} more (\`spelunk risks --kind ${g.kind}\`)`);
    out.push("");
  }

  if (r.tests.length) {
    out.push("## Tests", "", "| Test | Covers |", "|---|---|", ...r.tests.slice(0, 60).map((t) => `| ${link(t.path)} | ${t.covers.slice(0, 4).map((c) => `\`${c}\``).join(", ")}${t.covers.length > 4 ? ", …" : ""} |`), "");
  }

  if (r.overview?.glossary.length) out.push("## Glossary", "", ...r.overview.glossary.map((g) => `- **${g.term}**: ${g.meaning}`), "");
  return out.join("\n");
}
